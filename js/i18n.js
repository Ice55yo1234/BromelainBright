// --- i18n Engine ---
function getCurrentLang() {
  return localStorage.getItem('bb_lang') || 'en';
}

function setLang(lang) {
  localStorage.setItem('bb_lang', lang);
  applyTranslations(lang);
  updateLangToggle(lang);
  document.documentElement.lang = lang === 'th' ? 'th' : 'en';
}

function toggleLang() {
  const current = getCurrentLang();
  setLang(current === 'en' ? 'th' : 'en');
}

function t(key) {
  const lang = getCurrentLang();
  return TRANSLATIONS[lang]?.[key] || TRANSLATIONS['en']?.[key] || key;
}

function applyTranslations(lang) {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS['en'];

  // Translate elements with data-i18n attribute
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = dict[key];
      } else {
        el.innerHTML = dict[key];
      }
    }
  });

  // Translate elements with data-i18n-title (for tooltips)
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    if (dict[key]) el.title = dict[key];
  });
}

function updateLangToggle(lang) {
  const btn = document.getElementById('lang-toggle');
  if (btn) {
    btn.innerHTML = lang === 'en' ? '🇹🇭 ไทย' : '🇬🇧 EN';
    btn.title = lang === 'en' ? 'เปลี่ยนเป็นภาษาไทย' : 'Switch to English';
  }
}

// Initialize on page load
document.addEventListener('DOMContentLoaded', () => {
  const lang = getCurrentLang();
  applyTranslations(lang);
  updateLangToggle(lang);
  document.documentElement.lang = lang === 'th' ? 'th' : 'en';
});
